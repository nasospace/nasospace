/** Look up a workshop by its URL slug */
export function getWorkshopBySlug(slug: string): WorkshopDetail | undefined {
  return MOCK_WORKSHOPS.find((w) => w.slug === slug);
}

/** Get related workshops — same category first, then random fill */
export function getRelatedWorkshops(
  workshop: WorkshopDetail,
  limit = 3
): WorkshopDetail[] {
  const sameCategory = MOCK_WORKSHOPS.filter(
    (w) => w.id !== workshop.id && w.category === workshop.category
  );
  const others = MOCK_WORKSHOPS.filter(
    (w) => w.id !== workshop.id && w.category !== workshop.category
  );
  return [...sameCategory, ...others].slice(0, limit);
}
